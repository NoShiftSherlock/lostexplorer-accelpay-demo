import json, re, collections, sys, os
SP=sys.argv[1]; OUT=sys.argv[2]
var=[json.loads(r['j']) for r in json.load(open(SP+'/lc_variants.json'))]
# Excluded on request: retailers that already fulfil the brand's current store.
EXCLUDE=('vista wine','longhorn','mashbill')
var=[v for v in var if not v['is_gopuff'] and (v['stock'] or 0)>0 and v['synced']>='2026-09-01'
     and not any(k in v['rname'].lower() for k in EXCLUDE)]
UPC={'05391537970023':'espadin-750','05391537970061':'tobala-750','05391537970092':'salmiana-750',
     '00840202272184':'madre-cuishe-750','00840202272146':'blanco-750','00840202272153':'reposado-750',
     '05391537970269':'espadin-200','05391537970252':'tobala-200','05391537970245':'salmiana-200'}
def disp(n):
    n=re.sub(r'^Specs (\d+)$',r"Spec's #\1",n)
    n=n.replace(' - Shipping','').replace(' - (Shipping)','').replace('CORKED','Corked')
    return n
def cityfix(c): return {'Gavelston':'Galveston','Hunstville':'Huntsville','Wollforth':'Wolfforth','Nacodoches':'Nacogdoches'}.get(c,c)
R={}; V=collections.defaultdict(list)
for v in var:
    sku=UPC.get(v['upc'])
    if not sku: continue
    rid='r'+str(abs(hash((v['rname'],v['city'])))%10**8)
    rid=re.sub(r'[^a-z0-9]','',(disp(v['rname'])+v['city']).lower())[:24]
    R[rid]={'id':rid,'name':disp(v['rname']),'city':cityfix(v['city']),'state':v['state']}
    V[sku].append({'r':rid,'price':v['price'],'stock':v['stock'] if v['stock']<1000 else None,'synced':v['synced'][:10]})
# dedupe: keep cheapest per retailer per sku
for k in V:
    best={}
    for x in V[k]:
        if x['r'] not in best or x['price']<best[x['r']]['price']: best[x['r']]=x
    V[k]=sorted(best.values(),key=lambda x:x['price'])
# drop price outliers (likely mis-keyed retailer rows), < 55% of the SKU median
import statistics
dropped=[]
for k in V:
    med=statistics.median([x['price'] for x in V[k]])
    keep=[x for x in V[k] if x['price']>=0.55*med]
    dropped+=[(k,R[x['r']]['name'],x['price']) for x in V[k] if x['price']<0.55*med]
    V[k]=keep
print('dropped outliers',dropped)
R={rid:r for rid,r in R.items() if any(x['r']==rid for k in V for x in V[k])}
# Gopuff zips (live-confirmed stocked locations)
g=json.load(open(os.path.expanduser('~/.accelpay-ai-tools/cpg-coverage/data/the-lost-explorer/gopuff.json')))
gz=collections.defaultdict(list)
for r in g['results']:
    if r['stocked']:
        for z in r.get('delivery_zips') or []: gz[str(z).zfill(5)].append(r.get('city'))
GZ={z:c[0] for z,c in gz.items()}
GP={'blanco-750':5999,'reposado-750':6999,'tobala-750':14999,'salmiana-750':16999,'espadin-750':7499}
# zip prefix -> state
import pgeocode
nomi=pgeocode.Nominatim('us')
df=nomi._data
pref=collections.defaultdict(collections.Counter)
for z,s in zip(df['postal_code'],df['state_code']):
    if isinstance(s,str): pref[str(z).zfill(5)[:3]][s]+=1
P={p:c.most_common(1)[0][0] for p,c in pref.items()}
js='/* Generated by gen_data.py on 2026-10-24. Real data, see README "Data sources". Do not hand-edit. */\n'
js+='window.LE_DATA = '+json.dumps({'retailers':R,'variants':V,'gopuffZips':GZ,'gopuffPrices':GP,'zipPrefixState':P},separators=(',',':'))+';\n'
open(OUT,'w').write(js)
print(len(R),'retailers', {k:len(v) for k,v in V.items()}, len(GZ),'gp zips', len(P),'prefixes', len(js)//1024,'KB')
print(collections.Counter(r['state'] for r in R.values()))
